/* Bundles the notify-run core (src/server/notify + src/shared, fr.json inlined)
 * into one ESM file the Deno Edge Function imports. supabase-js and web-push
 * are not bundled: the function imports them itself (npm: specifiers).
 * Fails if the bundle would need a Node built-in the edge runtime lacks. */
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';

const outfile = 'supabase/functions/notify-run/core.js';

await build({
  entryPoints: ['src/server/notify/edge.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  outfile,
  legalComments: 'none',
  banner: { js: '/* Generated by scripts/build-notify.mjs — do not edit. */' },
  logLevel: 'warning',
});

const code = readFileSync(outfile, 'utf8');
const bad = code.match(/\bfrom\s+["']node:[^"']+["']|\brequire\(\s*["'][^"']+["']\s*\)|\bimport\(\s*["']node:/g);
if (bad) {
  console.error(`build-notify: ${outfile} still imports ${[...new Set(bad)].join(', ')}`);
  process.exit(1);
}
console.log(`build-notify: ${outfile} (${(code.length / 1024).toFixed(1)} kB)`);
